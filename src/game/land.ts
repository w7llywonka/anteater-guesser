let grid: Uint8Array | null = null;

function decode(): Uint8Array {
  const g = new Uint8Array(ROWS * 360);
  let i = 0;
  for (let r = 0; r < ROWS; r++) {
    let c = 0;
    let v = 0;
    while (c < 360) {
      let n = 0;
      let k: number;
      do {
        k = A.indexOf(RLE[i++]);
        n += k;
      } while (k === 63);
      if (v) g.fill(1, r * 360 + c, r * 360 + c + n);
      c += n;
      v ^= 1;
    }
  }
  return g;
}

export function isLand(lat: number, lng: number): boolean {
  grid ??= decode();
  const r = Math.floor(TOP - lat);
  const c = Math.floor(lng + 180);
  if (r < 0 || r >= ROWS || c < 0 || c >= 360) return false;
  return grid[r * 360 + c] === 1;
}
